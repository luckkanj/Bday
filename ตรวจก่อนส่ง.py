#!/usr/bin/env python3
"""
ตรวจความเรียบร้อยก่อนอัปขึ้นเว็บ

รัน:  python3 ตรวจก่อนส่ง.py

ทำไมต้องมี
  เว็บนี้ออกแบบให้ "กลืน" ความผิดพลาดเรื่องไฟล์หาย — รูปที่โหลดไม่ได้จะถูกข้าม
  เงียบ ๆ เพลงที่ไม่มีก็แค่ไม่มีเสียง เพื่อไม่ให้จอขาวต่อหน้าคนรับ
  ข้อเสียคือถ้าไฟล์หายจริง เราจะไม่รู้เลยจนกว่าจะนั่งดูจนจบ
  สคริปต์นี้จึงไล่ตรวจให้ครบก่อนส่ง
"""

import os
import re
import sys
from pathlib import Path

ที่นี่ = Path(__file__).resolve().parent
ผิด = []
เตือน = []


def หัวข้อ(ข้อความ):
    print(f"\n{ข้อความ}\n" + "─" * 58)


def main() -> int:
    เนื้อ = (ที่นี่ / "content.js").read_text(encoding="utf-8")

    # ── สื่อในสไลด์ ──────────────────────────────────────────
    หัวข้อ("สื่อในสไลด์")
    สื่อ = re.findall(r'(รูป|วิดีโอ)\s*:\s*"([^"]+)"', เนื้อ)
    ขนาดรวม = 0

    for ชนิด, พาธ in สื่อ:
        ไฟล์ = ที่นี่ / พาธ
        if ไฟล์.is_file():
            kb = ไฟล์.stat().st_size / 1024
            ขนาดรวม += kb
            ธง = "  ⚠ ใหญ่" if kb > 800 else ""
            print(f"  ✔ {ชนิด:6} {พาธ:16} {kb:7,.0f} KB{ธง}")
            if kb > 800:
                เตือน.append(f"{พาธ} ใหญ่ {kb:,.0f} KB")
        else:
            print(f"  ✘ {ชนิด:6} {พาธ:16} ไม่มีไฟล์นี้")
            ผิด.append(f"ไม่มีไฟล์ {พาธ}")

    # ── เพลง ────────────────────────────────────────────────
    หัวข้อ("เพลง")
    ม = re.search(r'เพลง:\s*\{.*?ไฟล์:\s*"([^"]+)"', เนื้อ, re.S)
    if not ม:
        print("  ✘ อ่านชื่อไฟล์เพลงจาก content.js ไม่ได้")
        ผิด.append("อ่านชื่อไฟล์เพลงไม่ได้")
    else:
        เพลง = ที่นี่ / ม.group(1)
        if เพลง.is_file():
            kb = เพลง.stat().st_size / 1024
            ขนาดรวม += kb
            print(f"  ✔ {ม.group(1):24} {kb:7,.0f} KB")
        else:
            print(f"  ✘ {ม.group(1):24} ไม่มีไฟล์นี้ — เว็บจะเงียบสนิทโดยไม่แจ้งอะไร")
            ผิด.append(f"ไม่มีไฟล์เพลง {ม.group(1)}")

    # ── ไฟล์ที่ไม่ได้ใช้ ──────────────────────────────────────
    หัวข้อ("ไฟล์ที่มีแต่ไม่ได้เรียกใช้")
    ใช้ = {p for _, p in สื่อ}
    เหลือ = sorted(
        str(f.relative_to(ที่นี่))
        for d in ("img", "vid")
        for f in (ที่นี่ / d).glob("*")
        if f.is_file() and str(f.relative_to(ที่นี่)) not in ใช้
    )
    if เหลือ:
        for f in เหลือ:
            print(f"  · {f}  (อัปขึ้นเว็บแต่ไม่มีใครเห็น)")
        เตือน.append(f"มีไฟล์ไม่ได้ใช้ {len(เหลือ)} ไฟล์")
    else:
        print("  ไม่มี")

    # ── ความยาว ─────────────────────────────────────────────
    หัวข้อ("ความยาวและขนาด")
    วิ = sum(int(x) for x in re.findall(r"วินาที:\s*(\d+)", เนื้อ))
    print(f"  สไลด์ {len(สื่อ)} ช่อง · ยาวรวม {อ่านเวลา(วิ)}")
    print(f"  ขนาดที่คนรับต้องโหลด {ขนาดรวม/1024:.2f} MB")
    if ขนาดรวม / 1024 > 8:
        เตือน.append(f"หนัก {ขนาดรวม/1024:.1f} MB — เน็ตมือถืออาจรอนาน")
    if วิ > 120:
        เตือน.append(f"สไลด์ยาว {อ่านเวลา(วิ)} — อาจนานเกินไป")

    # ── ของที่ไม่ควรขึ้นเว็บ ──────────────────────────────────
    หัวข้อ("ของที่ไม่ควรอัปขึ้นเว็บ")
    # ไม่ต้องสนใจใน _ต้นฉบับ/ เพราะทั้งโฟลเดอร์ไม่ถูกอัปอยู่แล้ว
    ขยะ = [str(f.relative_to(ที่นี่)) for f in ที่นี่.rglob("*")
           if f.is_file() and ":Zone.Identifier" in f.name
           and "_ต้นฉบับ" not in f.parts]
    ทดสอบ = sorted(str(f.name) for f in ที่นี่.glob("_test-*.html"))
    if ขยะ:
        for f in ขยะ:
            print(f"  ⚠ {f}  (เศษไฟล์ Windows — อยู่ใน .gitignore แล้ว)")
    if ทดสอบ:
        print(f"  · หน้าทดสอบ {len(ทดสอบ)} ไฟล์ — อยู่ใน .gitignore แล้ว ไม่ขึ้นเว็บ")
    if not ขยะ and not ทดสอบ:
        print("  ไม่มี")

    # ── สรุป ────────────────────────────────────────────────
    print("\n" + "═" * 58)
    if ผิด:
        print("ยังส่งไม่ได้ — ต้องแก้ก่อน:")
        for x in ผิด:
            print(f"  ✘ {x}")
    else:
        print("ผ่านหมด พร้อมอัปขึ้นเว็บ ✔")
    if เตือน:
        print("\nข้อควรพิจารณา (ไม่ถึงกับผิด):")
        for x in เตือน:
            print(f"  ⚠ {x}")
    print("═" * 58)

    return 1 if ผิด else 0


def อ่านเวลา(วิ: int) -> str:
    return f"{วิ//60} นาที {วิ%60} วินาที" if วิ >= 60 else f"{วิ} วินาที"


if __name__ == "__main__":
    sys.exit(main())
