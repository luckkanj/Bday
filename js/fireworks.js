/* ══════════════════════════════════════════════════════════════
   เครื่องยนต์พลุ

   วาดบน canvas ชั้นเดียวที่คลุมทั้งจอ
   เทคนิคสำคัญสองอย่าง:

   1) ลบภาพเก่าด้วย destination-out แทนการ clear ทั้งจอ
      อนุภาคจึงทิ้งหางจาง ๆ ไว้ แต่พื้นหลังยังโปร่งให้เห็นดาวข้างหลัง

   2) วาดด้วย composite 'lighter' แสงจึงบวกกันเวลาซ้อน
      เหมือนพลุจริงที่ตรงกลางสว่างกว่าขอบ

   ไม่ต้องแก้ไฟล์นี้เพื่อเปลี่ยนเนื้อหา — เนื้อหาอยู่ที่ content.js
   ══════════════════════════════════════════════════════════════ */

const พลุ = (function () {

  const cv  = document.getElementById('พลุ');
  const ctx = cv.getContext('2d');

  let กว้าง = 0, สูง = 0;
  let จรวด = [], ผง = [];
  let เฟรม = null;
  let โหมดเบา = false;          // โหมดฉากหลังตอนเล่นสไลด์
  let ตัวนับเบา = 0;

  const มือถือ = Math.min(window.innerWidth, window.innerHeight) < 600;
  const เพดานผง = มือถือ ? 900 : 1800;   // กันเครื่องอืด

  const ชุดสีทอง  = ['#fff3d0', '#f0c56a', '#ffb347', '#ffd97d'];
  const ชุดสีหวาน = ['#ffd0d8', '#ff8fa3', '#c9a7ff', '#8fd4ff'];
  const ชุดสีหัวใจ = ['#ffffff', '#ffd0d8', '#ff8fa3', '#ff4d6d'];

  /* ───────────── ขนาดจอ ───────────── */

  function วัดจอ() {
    const dpr = Math.min(window.devicePixelRatio || 1, 2);   // เกิน 2 ไม่คุ้มค่าแรงเครื่อง
    const w = Math.floor(window.innerWidth  * dpr);
    const h = Math.floor(window.innerHeight * dpr);

    // การเขียนค่า cv.width ล้างภาพบน canvas ทิ้งทั้งหมด
    // มือถือยิง resize รัว ๆ เวลาแถบที่อยู่เว็บยืดหด ถ้าไม่กันไว้
    // พลุจะกะพริบหายทุกครั้งที่เลื่อนนิ้ว
    if (cv.width === w && cv.height === h) return;

    กว้าง = window.innerWidth;
    สูง   = window.innerHeight;
    cv.width  = w;
    cv.height = h;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  }

  window.addEventListener('resize', วัดจอ);
  วัดจอ();

  /* ───────────── รูปหัวใจ ─────────────
     สมการหัวใจคลาสสิก
       x = 16 sin³t
       y = 13 cos t − 5 cos2t − 2 cos3t − cos4t
     รัศมีไกลสุดของเส้นนี้ประมาณ 17 จึงหารด้วย 17 ให้เหลือ 0–1
     แล้วค่อยคูณความเร็วที่ต้องการ                                */

  function ทิศหัวใจ(จำนวน) {
    const out = [];
    for (let i = 0; i < จำนวน; i++) {
      const t = (i / จำนวน) * Math.PI * 2;
      const x =  16 * Math.pow(Math.sin(t), 3);
      const y = -(13 * Math.cos(t) - 5 * Math.cos(2*t) - 2 * Math.cos(3*t) - Math.cos(4*t));
      out.push([x / 17, y / 17]);
    }
    return out;
  }

  /* ───────────── อนุภาค ───────────── */

  function เกิดผง(x, y, vx, vy, สี, อายุ, ขนาด, โน้ม) {
    if (ผง.length >= เพดานผง) return;
    ผง.push({
      x, y, vx, vy, สี,
      อายุ: อายุ, อายุเต็ม: อายุ,
      ขนาด: ขนาด,
      โน้ม: โน้ม === undefined ? 1 : โน้ม,
    });
  }

  const สุ่มใน = (arr) => arr[(Math.random() * arr.length) | 0];

  /* ───────────── การระเบิด ───────────── */

  // ระเบิดทรงกลมปกติ
  function ระเบิดกลม(x, y, สีชุด) {
    const จำนวน = มือถือ ? 70 : 120;
    const แรง   = 3.4 + Math.random() * 2.2;
    for (let i = 0; i < จำนวน; i++) {
      const มุม = Math.random() * Math.PI * 2;
      // รากที่สองทำให้อนุภาคกระจายทั่วทรงกลม ไม่กองที่ขอบ
      const ว = แรง * Math.sqrt(Math.random());
      เกิดผง(
        x, y,
        Math.cos(มุม) * ว,
        Math.sin(มุม) * ว,
        สุ่มใน(สีชุด),
        58 + Math.random() * 34,
        1 + Math.random() * 1.6
      );
    }
  }

  // ระเบิดเป็นรูปหัวใจ — ลูกเด่นของงานนี้
  function ระเบิดหัวใจ(x, y) {
    const จุด = ทิศหัวใจ(มือถือ ? 110 : 170);
    const แรง = มือถือ ? 3.6 : 4.6;

    จุด.forEach(([dx, dy], i) => {
      // กระจายเล็กน้อยไม่ให้เส้นคมเกินจนดูเป็นกราฟิก
      const ส = 0.94 + Math.random() * 0.12;
      เกิดผง(
        x, y,
        dx * แรง * ส,
        dy * แรง * ส,
        i % 7 === 0 ? '#ffffff' : สุ่มใน(ชุดสีหัวใจ),
        105 + Math.random() * 30,     // อยู่นานกว่าลูกอื่นให้ทันอ่านรูปทรง
        1.5 + Math.random() * 1.5,
        0.34                          // ตกช้ากว่าลูกอื่น รูปหัวใจจึงค้างอยู่
      );
    });

    // แกนกลางสว่างวาบตอนระเบิด
    for (let i = 0; i < 26; i++) {
      const มุม = Math.random() * Math.PI * 2;
      const ว = Math.random() * 1.5;
      เกิดผง(x, y, Math.cos(มุม)*ว, Math.sin(มุม)*ว, '#ffffff', 26, 2.2, 0.2);
    }
  }

  /* ───────────── จรวด ───────────── */

  function ยิง(ตัวเลือก) {
    const o = ตัวเลือก || {};
    const x  = o.x  !== undefined ? o.x  : กว้าง * (0.18 + Math.random() * 0.64);
    const เป้า = o.y !== undefined ? o.y : สูง * (0.16 + Math.random() * 0.3);

    จรวด.push({
      x,
      y: สูง + 12,
      vx: (Math.random() - 0.5) * 0.7,
      vy: -(Math.sqrt(2 * 0.085 * (สูง - เป้า))),   // คำนวณความเร็วต้นให้ถึงเป้าพอดี
      เป้า,
      แบบ: o.แบบ || 'กลม',
      สีชุด: o.สีชุด || (Math.random() < 0.65 ? ชุดสีทอง : ชุดสีหวาน),
      สีหาง: o.แบบ === 'หัวใจ' ? '#ff8fa3' : '#ffd97d',
    });
  }

  function ยิงหัวใจ(ตัวเลือก) {
    const o = ตัวเลือก || {};
    ยิง({
      x: o.x !== undefined ? o.x : กว้าง * 0.5,
      y: o.y !== undefined ? o.y : สูง * 0.33,
      แบบ: 'หัวใจ',
    });
  }

  /* ───────────── ลูปวาด ───────────── */

  function รอบ() {
    // จางภาพเก่าโดยไม่ทึบพื้นหลัง — นี่คือที่มาของหางพลุ
    ctx.globalCompositeOperation = 'destination-out';
    ctx.fillStyle = 'rgba(0,0,0,0.155)';
    ctx.fillRect(0, 0, กว้าง, สูง);

    ctx.globalCompositeOperation = 'lighter';

    /* จรวด */
    for (let i = จรวด.length - 1; i >= 0; i--) {
      const j = จรวด[i];
      j.x += j.vx;
      j.y += j.vy;
      j.vy += 0.085;

      // หางควันของจรวด
      เกิดผง(j.x, j.y, (Math.random()-0.5)*0.35, Math.random()*0.35,
             j.สีหาง, 20, 1.1, 0.35);

      ctx.fillStyle = j.สีหาง;
      ctx.beginPath();
      ctx.arc(j.x, j.y, 2, 0, Math.PI * 2);
      ctx.fill();

      // ถึงจุดสูงสุดแล้ว (เริ่มตก) หรือถึงเป้า → ระเบิด
      if (j.vy >= 0 || j.y <= j.เป้า) {
        if (j.แบบ === 'หัวใจ') ระเบิดหัวใจ(j.x, j.y);
        else                   ระเบิดกลม(j.x, j.y, j.สีชุด);
        จรวด.splice(i, 1);
      }
    }

    /* อนุภาค */
    for (let i = ผง.length - 1; i >= 0; i--) {
      const p = ผง[i];
      p.x  += p.vx;
      p.y  += p.vy;
      p.vx *= 0.986;                 // แรงต้านอากาศ
      p.vy  = p.vy * 0.986 + 0.042 * p.โน้ม;
      p.อายุ--;

      if (p.อายุ <= 0) { ผง.splice(i, 1); continue; }

      const จาง = p.อายุ / p.อายุเต็ม;
      ctx.globalAlpha = จาง * จาง;    // ยกกำลังสองให้ดับนุ่ม ไม่ตัดจบห้วน
      ctx.fillStyle = p.สี;
      ctx.beginPath();
      ctx.arc(p.x, p.y, p.ขนาด * (0.35 + จาง * 0.65), 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.globalAlpha = 1;

    /* โหมดเบา: ยิงประปรายเป็นฉากหลังตอนดูสไลด์ */
    if (โหมดเบา && --ตัวนับเบา <= 0) {
      ตัวนับเบา = 150 + Math.random() * 190;
      ยิง({ y: สูง * (0.12 + Math.random() * 0.22) });
    }

    เฟรม = requestAnimationFrame(รอบ);
  }

  /* ───────────── ชุดพลุตอนเปิดฉาก ───────────── */

  function ชุดใหญ่() {
    const หน่วง = (ms, fn) => setTimeout(fn, ms);

    หน่วง(0,    () => ยิง({ x: กว้าง * 0.5, y: สูง * 0.28 }));   // ลูกเปิด
    หน่วง(950,  () => ยิงหัวใจ());                               // หัวใจ ลูกเด่น
    หน่วง(2400, () => ยิง({ x: กว้าง * 0.22 }));
    หน่วง(2750, () => ยิง({ x: กว้าง * 0.78 }));
    หน่วง(3500, () => ยิง({ x: กว้าง * 0.4  }));
    หน่วง(3800, () => ยิง({ x: กว้าง * 0.62 }));
    หน่วง(4700, () => ยิงหัวใจ({ x: กว้าง * 0.3,  y: สูง * 0.42 }));
    หน่วง(5100, () => ยิงหัวใจ({ x: กว้าง * 0.72, y: สูง * 0.24 }));

    // ชุดรัวปิดท้าย
    for (let i = 0; i < 7; i++) หน่วง(6200 + i * 260, () => ยิง({}));
  }

  /* ───────────── ปุ่มควบคุมจากภายนอก ───────────── */

  return {
    เริ่ม() { if (!เฟรม) รอบ(); },
    หยุด()  { if (เฟรม) { cancelAnimationFrame(เฟรม); เฟรม = null; } },
    ยิง,
    ยิงหัวใจ,
    ชุดใหญ่,
    เบา(เปิด) { โหมดเบา = !!เปิด; ตัวนับเบา = 90; },
    ล้าง() {
      จรวด = []; ผง = [];
      ctx.clearRect(0, 0, กว้าง, สูง);
    },
  };

})();
